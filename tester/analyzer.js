/* ТЕСТЕР — аналіз коментарів на телефоні (без інтернету).
   Розбиває живу мову на окремі думки, враховує заперечення («не погано», «не дуже класно»,
   «багів немає»), протиставлення («але», «зате») і порівнює вагу позитиву та негативу. */
(function (root) {
  'use strict';

  const FILLERS = /^(ну|ее+|е+м+|мм+|ага|так|от|ось|вот|короче|коротше|типу|типа|як би|как бы|ладно|окей|ок|ok|значить|значит|блін|блин|слухай|слушай|загалом|в общем|взагалі то|поїхали|поехали|далі|дальше|давай далі|давай дальше|продовжуємо|продолжаем)$/i;
  const LEAD_FILLER = /^(?:(?:ну|ее+|мм+|короче|коротше|типу|типа|слухай|слушай|так|от|ось|вот|значить|значит|блін|блин)[\s,]+)+/i;

  // ключові основи слів (порівнюються з початком кожного слова)
  const POS = ['подоба','нрав','сподоба','класн','клас','круто','крут','кльов','клев','супер','чудов','чудес','отличн','відмінн','гарн','гарно','красив','прикольн','прикол','зручн','удобн','кайф','вау','топов','топ','бомб','шикарн','приємн','приятн','цікав','интересн','весел','смішн','смешн','плавн','добре','хорош','норм','люблю','обожн','вдал','зачет','зачот','вогонь','огонь','атмосферн','круть','офигенн','охрен','неймовірн','невероятн','ідеальн','идеальн','чітк','четк','швидк','быстр','good','nice','cool','love','awesome','great','perfect','like'];
  const NEG = ['погано','погана','поганий','погане','плохо','плох','жах','ужас','бісит','бесит','дратує','дратуют','раздраж','нудн','скучн','незручн','неудобн','крив','відстій','отстой','повільн','медлен','дивн','странн','некрасив','бідн','слабк','слаб','гірш','хуж','заважа','мешает','мешают','напряг','напряжн','заплутан','запутан','важк','тяжел','сумн','тупо','туп','дурн','бред','маячн','надоїда','надоеда','складн','сложн','темн','дрібн','мелк','криво','сир','сыр','нечитабел','перебор','тих','глух','hate','bad','annoying','boring','ugly','slow','weird'];
  const NEG_PHRASE = /(занадто|слишком|забагато|замало|не вистача|не хвата|не зрозуміл|не понятн|непонятн|незрозуміл|не видно|не чути|не слышно|не відчува|не ощущ|не подоба|не нрав|не сподоба|так собі|так себе|не дуже|не очень|ні про що|ни о чем|не те|не то)/i;
  const BUG_PHRASE = /(не працю|не работа|не спрацьов|не срабат|не реагу|не нажима|не натиска|не тисне|не відкрива|не открыва|не запуска|не зберіга|не сохраня|не завантаж|не загруж|не можу (пройти|натиснути|вийти|відкрити|зберегти)|не могу (пройти|нажать|выйти|открыть|сохранить)|чорний екран|черный экран|білий екран|белый экран|сам по собі|сам по себе|само по себе|провалив|провалил|провалюєть|проваливает|застряг|застрял|застряє|застревает|просіда|проседа|пропада|пропал|исчеза|зника|злетіл|слетел|скида|сбрасыва|дубл|мерехт|мерца|сіпа|дерга)/i;
  const BUG = ['баг','глюк','глюч','лаг','лага','лагу','завис','зависа','виліт','вилета','вилетіл','вылет','вылета','краш','крэш','crash','bug','фриз','фриза','гальм','тормоз','фпс','fps','помилк','ошибк','зламал','зламан','сломал','сломан','error','freez','lag'];
  const IDEA = /(треба|потрібно|потрібен|потрібна|нужно|нужен|нужна|надо|варто|стоит|слід|следует|хочу|хотілось|хотелось|хотів би|хотел бы|хочеться|хочется|краще б|лучше б|краще було б|краще зробити|лучше сделать|було б (добре|класно|круто|непогано|прикольно)|было бы (хорошо|классно|круто|неплохо|прикольно)|можна б|можно было|можна було б|давай(те)? (додамо|зробимо|добавим|сделаем)|додати|додайте|додав би|добав|зробити|зробіть|зробив би|сделать|сделайте|сделал бы|пропоную|предлагаю|змінити|змініть|изменить|поміняти|поменять|замінити|заменить|прибрати|приберіть|убрать|уберите|збільшити|зменшити|увеличить|уменьшить|пришвидшити|ускорить|сповільнити|замедлить|переробити|переделать|має бути|мало б|мала б|повинн|должн|хай буде|нехай буде|пусть будет|а якщо|а що якщо|а что если|should|would be|need to|add a|add an|make it)/i;
  const KEEP = /(залиш\S*\s+(?:\S+\s+){0,3}як є|остав\S*\s+(?:\S+\s+){0,3}как есть|не чіпа|не трога|не міняти|не менять|нічого не міня|ничего не меня|keep it)/i;
  const NEGATORS = new Set(['не','ні','ни','нє','not','no','без','never']);
  const ABSENT_AFTER = /(нема|немає|нет|не було|не было|не бачу|не вижу|не помітив|не заметил|відсутн|отсутств)/i;
  const INTENS = /(критич|взагалі не|вообще не|неможливо|невозможно|постійно|постоянно|завжди|всегда|кожен раз|каждый раз|кожного разу|виліта|вылета|краш|дуже|очень|жахлив|ужасн|терміново|срочно|капець|кошмар|повністю|полностью|зовсім|совсем|гра не|игра не)/i;

  const AREAS = [
    ['Продуктивність', /лаг|фпс|fps|гальм|тормоз|завис|виліт|вылет|фриз|загрузк|завантаж|просіда|проседа|оптиміз|оптимиз|гріється|греется|батаре/i],
    ['Керування', /керуван|управлен|кнопк|джойстик|стриб|прыж|присід|присед|біг|бег|рух|движен|чутлив|чувствит|миш|мыш|клавіш|клавиш|приціл|прицел|стрільб|стрельб|свайп|тач|сенсор|геймпад/i],
    ['Камера', /камер|ракурс|огляд|обзор|зум|zoom|наближ|приближ/i],
    ['Звук', /звук|музик|музык|гучн|громк|тих|озвуч|голос|саунд|шум|постріл|выстрел/i],
    ['Інтерфейс', /меню|інтерфейс|интерфейс|шрифт|напис|надпис|текст|hud|худ|іконк|иконк|мінікарт|миникарт|карт[аиуі]\b|кнопочк|екран|экран|індикатор|индикатор|смужк|полоск|налаштуван|настройк/i],
    ['Графіка', /графік|графон|текстур|модел|анімац|анимац|світл|освітл|свет|колір|кольор|цвет|ефект|эффект|картинк|візуал|визуал|тін|тен|вибух|взрыв|частинк|частиц|деталізац|детализац|фон/i],
    ['Баланс', /складн|сложн|легк|баланс|урон|шкод|здоров|хп\b|hp\b|ворог|враг|бос|босс|зброя|зброї|оружи|патрон|нагород|награ|рівн|уровн|прокачк|досвід|опыт|монет|золот|економ|эконом|ціна|цена/i],
    ['Сюжет', /сюжет|діалог|диалог|квест|місі|мисси|персонаж|героя|героїн|історі|истори|катсцен|ролик|завдан|задани/i],
    ['Геймплей', /геймплей|механік|механик|гра в цілому|игра в целом|темп|динамік|динамик|нудн|скучн|цікав|интересн/i]
  ];

  const SPLIT_WORDS = '(?:але|проте|однак|однак ж|зате|тільки от|тільки|а от|хоча|хоча б|но|однако|зато|только вот|правда|but|however|although|а ще|і ще|ще й|а також|також|плюс до того|крім того|кроме того|ещё|а еще|и еще|потім|потом|далі|дальше|до речі|кстати|окремо|отдельно|і взагалі|и вообще|а взагалі|а вообще)';
  const SPLIT_RX = new RegExp('\\s+(?=' + SPLIT_WORDS + '\\s)', 'i');
  const BEFORE_IDEA_RX = /\s+(?:і|и|та|а|й|,)?\s*(?=(?:треба|потрібно|нужно|надо|хочу|хотілось|хотелось|давай|краще б|лучше б|варто|стоит|пропоную|предлагаю)\s)/i;
  const BEFORE_BUG_RX = /\s+(?:і|и|та|а|й)\s+(?=(?:ще\s+)?(?:баг|глюк|гра\s+(?:лагає|зависає|вилітає|гальмує)|игра\s+(?:лагает|зависает|вылетает|тормозит)|вилітає|вылетает|зависає|зависает)\b)/i;

  const norm = s => s.toLowerCase().replace(/ё/g, 'е').replace(/[’'`]/g, 'ʼ');
  const words = s => norm(s).split(/[^\p{L}\p{N}ʼ-]+/u).filter(Boolean);
  const hasStem = (w, list) => list.some(st => w.startsWith(st));

  function splitThoughts(text) {
    let parts = [text];
    const re = (arr, rx) => arr.flatMap(p => p.split(rx));
    parts = re(parts, /(?<=[.!?;…])\s+|\s*;\s*/);
    parts = re(parts, /,\s+(?=(?:але|проте|зате|а|но|однако|зато|хоча|тільки|только|і|и|та|а ще|ще)\s)/i);
    parts = re(parts, SPLIT_RX);
    parts = re(parts, BEFORE_IDEA_RX);
    parts = re(parts, BEFORE_BUG_RX);
    return parts.map(p => p.trim().replace(/^[,.\s-]+|[,\s-]+$/g, '')).filter(Boolean);
  }

  function cleanClause(c) {
    let s = c.replace(LEAD_FILLER, '').replace(/^(?:але|проте|однак|зате|тільки|а от|хоча|но|однако|зато|только вот|правда|but|however|а ще|і ще|ще й|а також|також|крім того|кроме того|ещё|а еще|и еще|до речі|кстати)\s+/i, '').replace(/\s+/g, ' ').trim();
    return s;
  }
  function isFiller(c) {
    const w = words(c);
    return !w.length || w.every(x => FILLERS.test(x)) || (w.length <= 2 && w.every(x => FILLERS.test(x) || x.length <= 2));
  }

  function score(clause) {
    const t = norm(clause);
    const w = words(clause);
    let pos = 0, neg = 0, bug = 0;
    const idea = IDEA.test(t);
    const keep = KEEP.test(t);

    // фрази-баги («не працює», «провалився»)
    if (BUG_PHRASE.test(t)) bug += 2;
    // фрази-негатив («не подобається», «занадто», «не видно»)
    if (NEG_PHRASE.test(t)) neg += 2;

    for (let i = 0; i < w.length; i++) {
      const x = w[i];
      const negated = (NEGATORS.has(w[i - 1]) || (NEGATORS.has(w[i - 2]) && /^(дуже|очень|сильно|особо|зовсім|совсем|надто|так)$/.test(w[i - 1] || '')));
      if (hasStem(x, BUG)) {
        // «багів немає», «без лагів», «не лагає»
        const after = w.slice(i + 1, i + 3).join(' ');
        if (negated || ABSENT_AFTER.test(after) || ABSENT_AFTER.test(w.slice(Math.max(0, i - 2), i).join(' '))) pos += 1; else bug += 2;
        continue;
      }
      if (hasStem(x, NEG)) { if (negated) pos += 1; else neg += 1; continue; }
      if (hasStem(x, POS)) {
        if (negated) neg += 1.5;
        else if (/^(дуже|очень|просто|реально|прям|сильно|so|really)$/.test(w[i - 1] || '')) pos += 1.5;
        else pos += 1;
      }
    }
    // «не подобається» вже пораховано у NEG_PHRASE — прибираємо подвійний плюс від «подоба»
    if (/не (дуже |очень )?(подоба|нрав|сподоба)/.test(t)) pos = Math.max(0, pos - 1);
    return { pos, neg, bug, idea, keep };
  }

  function classify(clause) {
    const s = score(clause);
    if (s.keep) return 'like';
    if (s.bug > 0 && s.bug >= s.pos) return 'bug';
    if (s.idea) return 'idea';
    if (s.neg > s.pos) return 'dislike';
    if (s.pos > s.neg) return 'like';
    if (s.pos > 0 && s.pos === s.neg) return 'dislike'; // змішане — краще переглянути
    return 'other';
  }

  function areaOf(t) { const a = AREAS.find(x => x[1].test(t)); return a ? a[0] : ''; }
  const cap = s => s.charAt(0).toUpperCase() + s.slice(1);

  function analyze(text, opts) {
    opts = opts || {};
    const groups = { bug: [], dislike: [], idea: [], like: [], other: [] };
    const seen = new Map();
    let prev = null;
    text.split('\n').forEach(raw => {
      let line = raw.trim(); if (!line) return;
      let tm = ''; const m = line.match(/^\[(\d{1,2}:\d{2})\]\s*/); if (m) { tm = m[1]; line = line.slice(m[0].length); }
      let lastArea = '';
      splitThoughts(line).forEach(part => {
        let c = cleanClause(part);
        if (isFiller(c)) return;
        let cat = classify(c);
        let area = areaOf(c);
        // короткий уточнювальний шматок без оцінки («особливо на мосту») — дописуємо до попередньої думки
        if (cat === 'other' && words(c).length <= 4 && prev) { prev.text += ', ' + c; return; }
        // «вона дуже повільна» після «камера…» — успадковуємо область
        if (!area && lastArea && /^(вона|він|воно|вони|она|он|оно|они|це|это|її|його|ее|его)\b/i.test(c)) area = lastArea;
        if (area) lastArea = area;
        const crit = (cat === 'bug' || cat === 'dislike') && INTENS.test(norm(c));
        const key = cat + '|' + norm(c).replace(/[^\p{L}\p{N}]+/gu, ' ').trim();
        if (seen.has(key)) { seen.get(key).times++; return; }
        const item = { cat, text: cap(c), area, crit, tm, times: 1 };
        seen.set(key, item); groups[cat].push(item); prev = item;
      });
    });
    ['bug', 'dislike'].forEach(k => groups[k].sort((a, b) => (b.crit ? 1 : 0) - (a.crit ? 1 : 0)));
    const fmtItem = it => (it.crit ? '❗ ' : '') + (it.area ? '[' + it.area + '] ' : '') + it.text + (it.times > 1 ? ' (сказано ' + it.times + ' рази)' : '') + (it.tm ? ' (' + it.tm + ')' : '');
    const SECTIONS = [['bug', '🐞 БАГИ'], ['dislike', '👎 НЕ ПОДОБАЄТЬСЯ'], ['idea', '💡 ІДЕЇ / ПОБАЖАННЯ'], ['like', '👍 ПОДОБАЄТЬСЯ (не чіпати)'], ['other', '📝 ІНШЕ / НОТАТКИ']];
    let out = (opts.header || '') + '\n';
    SECTIONS.forEach(([k, title]) => {
      out += '\n' + title + ' (' + groups[k].length + ')\n';
      groups[k].forEach((it, i) => out += (i + 1) + '. ' + fmtItem(it) + '\n');
      if (!groups[k].length) out += '—\n';
    });
    return { text: out.trim(), groups };
  }

  const api = { analyze, classify, splitThoughts, score };
  if (typeof module !== 'undefined' && module.exports) module.exports = api; else root.TesterAnalyzer = api;
})(typeof window !== 'undefined' ? window : this);
